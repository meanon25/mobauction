#!/usr/bin/env python3
"""Extract finite discovery IDs, never old recipe ingredients or skill ranks.

The installed AtlasLoot Forever package retains Classic/BCC data. These IDs are
only queries to make against the live client, not assertions that a recipe exists
in Forever. New Forever IDs are discovered from the player's profession lists
and item tooltips at runtime. No character SavedVariables are redistributed.
"""
import argparse
import re
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("atlas_profession", type=Path)
parser.add_argument("--output", type=Path, default=Path("MobAuction/CatalogueData.lua"))
args = parser.parse_args()
source = args.atlas_profession.read_text()
classic_bcc = source.split("PROFESSION_DATA.CLASSIC = {", 1)[1].split(
    "if AtlasLoot:GameVersion_GE(AtlasLoot.WRATH_VERSION_NUM)", 1
)[0]
ids = sorted({int(x) for x in re.findall(r"^\s*\[(\d+)\]\s*=\s*\{", classic_bcc, re.M) if int(x) > 0})
if len(ids) < 1000:
    raise SystemExit("Unexpected input: fewer than 1000 historical recipe candidates")
lines = [
    "-- Generated by tools/import_catalogue_candidates.py. IDs are discovery hints only.",
    "-- Source: installed AtlasLoot Forever 1.60.1, Data/Profession.lua CLASSIC/BCC tables.",
    "-- Blizzard game identifiers; no AtlasLoot implementation, ingredients or ranks copied.",
    "-- Every candidate requires independent current-client recipe/owner/schematic validation.",
    "-- This historical seed list is NOT a complete or verified Forever recipe catalogue.",
    "local _, F = ...",
    "F.catalogueCandidates = {",
]
for offset in range(0, len(ids), 14):
    lines.append("  " + ",".join(map(str, ids[offset:offset + 14])) + ",")
lines.extend(["}", ""])
args.output.write_text("\n".join(lines))
print(f"Wrote {len(ids)} candidate IDs to {args.output}; runtime validation is mandatory")
